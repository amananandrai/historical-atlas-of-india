// Writes js/monuments.js: the monuments the atlas pins on its map, taken from the monuments site's own
// list (js/data.js in https://github.com/amananandrai/monuments-of-india), so the two sites never disagree.
//
//   node tools/sync-monuments.mjs                         # from the monuments repo's main branch
//   node tools/sync-monuments.mjs ../monuments-of-india   # from a local checkout
//
// Only what the atlas shows is kept: id, name, place, built, year, type and position. A pin and the
// era card link to the monument's 3D model at MONUMENTS_SITE, and the card's picture comes from there.
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const SITE = 'https://monuments-of-india-nu.vercel.app';
const RAW = 'https://raw.githubusercontent.com/amananandrai/monuments-of-india/main/js/data.js';
const out = new URL('../js/monuments.js', import.meta.url);

const local = process.argv[2];
const source = local ? await readFile(join(resolve(local), 'js', 'data.js'), 'utf8') : await (await fetch(RAW)).text();
// data.js imports nothing and only refers to the monuments' builder files inside functions, so it can
// be loaded on its own from a temporary copy.
const tmp = join(await mkdtemp(join(tmpdir(), 'atlas-')), 'data.mjs');
await writeFile(tmp, source);
const { MONUMENTS } = await import(pathToFileURL(tmp).href);

const keep = MONUMENTS.map(({ id, name, place, built, year, type, lat, lng }) => {
  if (!Number.isFinite(year)) throw new Error(`${id} has no year`);
  return { id, name, place, built, year, type, lat, lng };
}).sort((a, b) => a.year - b.year || a.name.localeCompare(b.name));

await writeFile(out, `// The monuments pinned on the atlas. Generated by tools/sync-monuments.mjs from the monuments site's
// js/data.js; do not edit by hand.
export const MONUMENTS_SITE = '${SITE}';

export const MONUMENTS = [
${keep.map((m) => `  ${JSON.stringify(m)},`).join('\n')}
];
`);
console.log(`wrote js/monuments.js: ${keep.length} monuments`);
